#!/usr/bin/env python3
"""Keep secrets out of the ~/.hermes git repo.

  secrets.py redact   Write config.redacted.yaml (secret values replaced) and env.keys (variable names only).
  secrets.py scan     Pre-commit check: refuse the commit if any staged file contains a secret.

Secrets are recognized two ways: the actual values found in .env and config.yaml, and common token formats.
"""
import os, re, subprocess, sys

HOME = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))  # ~/.hermes (this file lives in ~/.hermes/ops)
CONFIG = os.path.join(HOME, "config.yaml")
ENV = os.path.join(HOME, ".env")
REDACTED = "<REDACTED>"

SECRET_KEY = re.compile(r"(key|token|secret|passw|authorization|bearer|credential|cookie|auth)", re.I)
B = r"(?<![A-Za-z0-9_\-])"   # token must start a word: "task-manager" is not an "sk-" key
TOKEN_PATTERNS = [
    re.compile(p) for p in [
        B + r"AIza[0-9A-Za-z_\-]{35}",                    # Google API key
        B + r"sk-(?:ant-|proj-)?[A-Za-z0-9_\-]{32,}",      # Anthropic / OpenAI style
        B + r"gh[pousr]_[A-Za-z0-9]{30,}",                 # GitHub
        B + r"github_pat_[A-Za-z0-9_]{20,}",
        B + r"fmu\d-[A-Za-z0-9\-]{20,}",                   # Fastmail API token
        B + r"xox[abprs]-[A-Za-z0-9\-]{10,}",              # Slack
        r"\b\d{8,10}:[A-Za-z0-9_\-]{35}\b",                # Telegram bot token
        B + r"AKIA[0-9A-Z]{16}",                           # AWS
        r"-----BEGIN [A-Z ]*PRIVATE KEY-----",
        r"[Bb]earer\s+[A-Za-z0-9._\-]{20,}",
        r"https?://[^/\s:@]+:[^/\s@]+@",                   # credentials in a URL
    ]
]
# Documentation examples ("sk-xxxx", "${GITHUB_TOKEN}", "<your-key>", "USER:PASSWORD") are not secrets.
PLACEHOLDER = re.compile(r"[$<{]|x{4,}|X{4,}|\.\.\.|your|example|dummy|redacted|placeholder|"
                         r"TOKEN|PASSWORD|SECRET|USER(NAME)?\b|API_KEY", re.I)


def real_tokens(text):
    """Token-format matches in text that look like real secrets, as (line number, match)."""
    hits = []
    for p in TOKEN_PATTERNS:
        for m in p.finditer(text):
            t = m.group(0)
            if "PRIVATE KEY" not in t:
                if PLACEHOLDER.search(t):
                    continue
                if not t.startswith("http") and sum(c.isdigit() for c in t) < 3:
                    continue  # real keys are random and contain digits; "sk-abcdefghijk..." is an example
            hits.append((text.count("\n", 0, m.start()) + 1, t))
    return hits


PLAIN = re.compile(r"^(true|false|null|none|yes|no|~|-?\d+(\.\d+)?)$", re.I)
KV = re.compile(r"^(\s*(?:-\s+)?)([\"']?[A-Za-z0-9_.\-]+[\"']?)(\s*[:=]\s*)(.*)$")


def unquote(v):
    v = v.strip()
    if len(v) >= 2 and v[0] == v[-1] and v[0] in "\"'":
        v = v[1:-1]
    return v


def is_secret_value(key, value):
    v = unquote(value.split(" #")[0])
    if not v or v in ("|", ">", "|-", ">-", "{}", "[]") or PLAIN.match(v):
        return False
    if v.startswith("${") or v == REDACTED:
        return False
    return bool(SECRET_KEY.search(key)) or any(p.search(v) for p in TOKEN_PATTERNS)


def redact_text(text):
    out, found = [], []
    for line in text.split("\n"):
        m = KV.match(line)
        if m and not line.lstrip().startswith("#") and is_secret_value(m.group(2), m.group(4)):
            found.append(unquote(m.group(4).split(" #")[0]))
            line = f"{m.group(1)}{m.group(2)}{m.group(3)}\"{REDACTED}\""
        else:
            for _, hit in real_tokens(line):
                found.append(hit)
                line = line.replace(hit, REDACTED)
        out.append(line)
    return "\n".join(out), found


def env_values():
    vals = []
    if os.path.exists(ENV):
        for line in open(ENV, errors="replace"):
            m = re.match(r"^\s*(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*)$", line)
            if m:
                vals.append((m.group(1), unquote(m.group(2))))
    return vals


def known_secrets():
    s = [v for n, v in env_values()
         if len(v) >= 8 and not PLAIN.match(v)
         and (SECRET_KEY.search(n) or (len(v) >= 20 and re.search(r"\d", v) and re.search(r"[A-Za-z]", v)
                                        and not re.search(r"[\s/]", v)))]
    if os.path.exists(CONFIG):
        s += [v for v in redact_text(open(CONFIG, errors="replace").read())[1] if len(v) >= 8]
    return sorted(set(s), key=len, reverse=True)


def cmd_redact():
    if os.path.exists(CONFIG):
        text, found = redact_text(open(CONFIG, errors="replace").read())
        header = ("# GENERATED by ops/secrets.py from config.yaml. Secret values are replaced with "
                  f"{REDACTED}.\n# To restore: copy to config.yaml and fill them in from your password manager.\n")
        open(os.path.join(HOME, "config.redacted.yaml"), "w").write(header + text)
        print(f"config.redacted.yaml written ({len(found)} values redacted)")
    names = [n for n, _ in env_values()]
    if names:
        open(os.path.join(HOME, "env.keys"), "w").write(
            "# GENERATED: variable names from .env (values are NOT stored here).\n"
            + "".join(f"{n}=\n" for n in names))
        print(f"env.keys written ({len(names)} names)")


def allowed_paths():
    """ops/secrets-allow.txt: one glob per line (e.g. skills/vendor/**). Token-format checks skip these files;
    the check for your real .env / config.yaml values still applies everywhere."""
    p = os.path.join(HOME, "ops", "secrets-allow.txt")
    if not os.path.exists(p):
        return []
    return [l.strip() for l in open(p) if l.strip() and not l.startswith("#")]


def cmd_scan():
    import fnmatch
    files = subprocess.run(["git", "diff", "--cached", "--name-only", "--diff-filter=ACMR", "-z"],
                           capture_output=True, text=True, cwd=HOME).stdout.split("\0")
    secrets = known_secrets()
    allow = allowed_paths()
    problems = []
    for f in filter(None, files):
        blob = subprocess.run(["git", "show", f":{f}"], capture_output=True, cwd=HOME).stdout
        if b"\0" in blob[:8000]:
            continue  # binary
        text = blob.decode("utf-8", "replace")
        leaked = [v for v in secrets if v in text]
        if leaked:
            line = text.count("\n", 0, text.index(leaked[0])) + 1
            problems.append(f"{f} line {line}: contains a value from your .env or config.yaml")
            continue
        if any(fnmatch.fnmatch(f, g) for g in allow):
            continue
        hits = real_tokens(text)
        if hits:
            line, t = hits[0]
            problems.append(f"{f} line {line}: looks like a secret ({t[:6]}...)")
    if problems:
        print("COMMIT BLOCKED: possible secrets in staged files:")
        for p in problems:
            print("  - " + p)
        print("If it's real, take it out (scripts read secrets from ~/.hermes/.env at run time).")
        print("If it's a false alarm in a file you didn't write, add the path to ~/.hermes/ops/secrets-allow.txt.")
        sys.exit(1)


if __name__ == "__main__":
    {"redact": cmd_redact, "scan": cmd_scan}.get(sys.argv[1] if len(sys.argv) > 1 else "",
        lambda: sys.exit("usage: secrets.py redact|scan"))()
